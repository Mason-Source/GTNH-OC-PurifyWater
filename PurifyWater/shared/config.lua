--------------------------------------------------------------------------------
-- shared/config.lua
--------------------------------------------------------------------------------
-- 【职责】全部**可调参数**集中在这一处：周期、文件名、循环节奏、镜像端口、默认阈值
-- 【不做什么】不含常量表（shared/constants.lua）、不含运行期数据（shared/state.lua）
-- 【依赖】无
-- 【被谁用】core/*、backend/*、frontend/*
-- 【用法】`local CONFIG = require("shared.config")` —— 直接返回这张表（不再包一层 {CONFIG=...}）
--------------------------------------------------------------------------------

local CONFIG                     = {}

-- ============================ 数据文件（**全部集中在 data/ 子目录**） ============================
-- 集中的理由：一个目录就能看全机器记了什么；备份/清理只动一处；父目录已是应用目录，
--   文件名不必再带前缀。程序自记的与给人手改的仍分文件：`levels.txt` 可直接编辑，
--   其余是程序专用格式（改坏会重建）。
-- 【路径解析】交 backend/store/files.path()：以 "/" 开头才是绝对路径，否则相对应用根目录；
--   目录不存在时写盘会自动创建（files.ensureDir）。
CONFIG.FILES                     = {
    RECORDS  = "data/records.txt",  -- 各等级实测并行 + 成功率
    LEVELS   = "data/levels.txt",   -- 阈值 + 勾选（**用户可手改**）
    HARDWARE = "data/hardware.txt", -- 硬件拓扑清单（有变化才写）
    HISTORY  = "data/history.dat",  -- 曲线点（一行一点）
    LOG      = "data/log.txt",      -- 日志（T5 每 30 秒把内存里的新行追加进来）
    SETTINGS = "data/settings.txt", -- 程序自己记的偏好（运行模式等）
    TRACE    = "data/last_run.txt"  -- 启动/退出痕迹 + 内存紧张时的留痕
}

-- ============================ 定时任务周期（秒） ============================
CONFIG.INTERVAL                  = {
    HARDWARE  = 10, -- T1 重扫机器（能源仓 / ME / T0-8 水厂）
    FLUID     = 5,  -- T2 读 1-8 级水缓存 + 阈值文件
    OBSERVE   = 5,  -- T3 读 T0-8 开关/运行；对在运行的 T1-8 读传感器
    SCHEDULE  = 5,  -- T4 贪心调度
    PERSIST   = 30, -- T5 脏数据落盘
    SAMPLE    = 1,  -- T6 内存峰值采样（**只在 --debug 下注册**，见决策 32：日常运行不装这个模块）
    BROADCAST = 1   -- T7 无线广播（门控：总开关 + 网卡在位）
}

-- ============================ 界面（可调） ============================
CONFIG.UI                        = {
    -- 配置页阈值上限（以 kL 计）：**1e14 及以上不接受**（含等于）。判据是运算后的**数值**
    --   而非位数 —— 倍数键一步就能跨过位数边界，按位数判会漏。
    MAX_THRESHOLD_KILO   = 100000000000000,
    -- 视图重建间隔：每帧重建（8 级 × 多字段 + 曲线统计）在 OC 上是浪费；0.25 秒足够跟手，
    --   面板另有指纹挡着（没变不画）。
    VIEW_REFRESH_SECONDS = 0.25,

    -- 字号由字符分辨率决定：格数越少字越大；填 0 = 不动屏幕。
    --   本机屏幕 160×50（tier 3 上限），这里保持 128×40（字体放大已放弃，紧凑度靠版面解决）。
    --   想放大就把这两项调小（如 112×36）；机制不变：启动 setResolution、退出还原。
    RESOLUTION_WIDTH     = 128,
    RESOLUTION_HEIGHT    = 40
}

-- ============================ 曲线 ============================
-- 【时间单位：os.time 的“秒”】实测（由 history.dat 反推）：
--   1 个采样点（T5 的 30 秒）在 os.time 上走 2160，即 1 游戏日 = 86400 os 秒。
--   os.time 是**游戏内时间**（暂停不前进），所以按时间差筛点成立。
-- 【只有采样点】报表页与小时/天聚合整条链已删，图表面板只看原始点。
-- 【POINTS = 最宽的时间窗口】内存与盘上都按它封顶，所以它只需盖住"看得见的那些天"：
--   全部 = 1 游戏日（40 点），单级曲线 = 2 游戏日（80 点）→ 80 点。
--   多留的点画不到，只白占内存（OC 的 Lua 堆上限由内存条决定）与盘。
CONFIG.CHART                     = {
    POINTS               = 80,    -- 曲线保留的原始点数 = 单级曲线的窗口（2 游戏日，30 秒一个）
    SECONDS_PER_GAME_DAY = 86400, -- 1 游戏日在 os.time 上的跨度（**时间窗口唯一换算处**）
    ALL_WINDOW_DAYS      = 1,     -- 「全部」柱状图看近几天
    LEVEL_WINDOW_DAYS    = 2      -- 单级曲线看近几天
}

-- ============================ 无线广播（镜像端） ============================
CONFIG.NET                       = {
    ENABLED = false, -- 总开关（界面按钮可切；关着时 T7 完全不动作）
    PORT    = 4096,  -- 无线端口
    CHUNK   = 4000,  -- 分片字节数（OC 单条消息上限 8192）
    REFRESH = 2      -- 镜像端"多久没收到数据"这句话的刷新间隔（秒）
}

-- ============================ 主循环 ============================
-- event.pull 的超时 = clamp(最近到期任务, MIN, MAX)
CONFIG.LOOP_MIN_IDLE             = 0.05
CONFIG.LOOP_MAX_IDLE             = 1.0

-- 【内存没有可调参数】OC 的沙箱里 `collectgarbage` 是 nil（实机报过
--   `attempt to call a nil value (global 'collectgarbage')`）：回收参数改不了，
--   也不能主动收。内存只能靠两件事控住：少造垃圾（视图缓存）、少留数据
--   （曲线/日志只留看得见的量，见 CONFIG.CHART.POINTS / CONFIG.LOG.MAX_LINES）。

-- ============================ 并行确认（domain/tracker） ============================
-- 并行的物理含义是“一台机器在一个完整配方里能吃多少水”：周期内恒定、只在周期之间变，
--   所以只有“连续 N 个**周期**同值”才算稳定（按秒数数是碰运气）。
--   周期边界 = `getWorkProgress` 回落（2400 刻 ≈ 2 分钟）。
CONFIG.PARALLEL_CONFIRM_CYCLES   = 3
--   退化口径：读不到进度时，攒够这么多次采样算“一个周期”
--   （T3 每 5 秒一次 → 24 次 ≈ 2 分钟，与真实周期同量级）。
CONFIG.PARALLEL_FALLBACK_SAMPLES = 24

-- ============================ 阈值文件默认值 ============================
-- 文件缺失/损坏时用它生成一份，并写一行提示（该文件可直接编辑）
-- 【新装默认：阈值 0 + 勾选】阈值 0 = “水位永不低于阈值” = 永不因阈值开启，除 5 倍线强制开
--   和原料不足两条硬规则外什么都不开 —— 刚接入时机器不乱动，等用户在配置页自己设数。
CONFIG.LEVELS_DEFAULT            = {
    threshold = 0,   -- 默认阈值 0（= 不因阈值开启）
    enabled   = true -- 默认全部勾选（勾选 = 该级受阈值管理）
}

-- ============================ 系统行为（决策项） ============================
CONFIG.SYSTEM                    = {
    -- 开机默认：优先级、是否自动开始调度
    -- 运行模式是永久配置：界面切换后立即存进 CONFIG.FILES.SETTINGS，下次启动沿用存的值；
    --   这里的默认值只在从未保存过时生效（删掉 settings 文件即回到这里）。
    PRIORITY_DEFAULT        = "low", -- "low" = 低级水优先 / "high" = 高级水优先
    START_ON_BOOT           = false, -- true = 程序一启动就自动开调度（无人值守机房用）

    -- 进安全状态（全关+锁定 / 仅锁定）后只保留只读逻辑（T1/T2/T3 采集、界面、日志），
    --   等用户手动点【启动系统】；没有自动恢复。
    RELEARN_ON_POWER_CHANGE = true, -- 换/加能源仓 -> 并行记录作废（下次重测）
    RELEARN_ON_UNIT_CHANGE  = true  -- 单元增删 -> 相关等级记录作废
}

-- ============================ 日志 ============================
CONFIG.LOG                       = {
    LEVEL      = "user", -- user | debug（--debug 打开）
    -- 【内存】只留"屏幕上放得下"的那几行（折行后 10 行 ≈ 一眼看到的一片）：
    --   超出就删**最前面**的行；面板仍从缓冲尾部取可见行数画。
    MAX_LINES  = 10,
    -- 【盘】`data/log.txt` 保留的行数（T5 每 30 秒把内存里的新行追加进去并裁到上限）：
    --   要翻旧账看这个文件 —— 它比屏幕上能显示的多得多，也不占内存。
    FILE_LINES = 200
}

return CONFIG
